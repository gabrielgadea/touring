#!/usr/bin/env python3
"""W8.6 — Generate touring-hooks/src/lib.rs façade with pub use re-exports.

After W8.1-W8.5 split touring-hooks into 8 sub-crates, the façade `touring-hooks`
crate becomes a thin re-export shell. This script reads the bucket map
(data/w8-hooks-split-plan.json) and emits the lib.rs that re-exports the
public API of each sub-crate.

Outputs:
  - staging/w8-touring-hooks-facade-lib.rs    (drop-in replacement for src/lib.rs)
  - staging/w8-touring-hooks-Cargo.toml       (updated [dependencies] only)
  - data/w8-facade-manifest.json

Usage
-----
    python3 w8_hooks_facade_emitter.py
    python3 w8_hooks_facade_emitter.py --plan data/w8-hooks-split-plan.json
"""
from __future__ import annotations

import json
from pathlib import Path

import script_common as sc

_SCRIPT = "w8_hooks_facade_emitter"

_ROOT, _DATA_DIR, _STAGING_DIR = sc.ROOT, sc.DATA_DIR, sc.STAGING_DIR


def build_parser() -> sc.ArgumentParser:
    """CLI parser."""
    p = sc.new_parser(_SCRIPT, __doc__)
    p.add_argument("--plan", type=Path,
                   default=_DATA_DIR / "w8-hooks-split-plan.json")
    return sc.with_output_dir_and_verbose(p, _DATA_DIR)


def emit_facade_lib(buckets: list[str]) -> str:
    """Generate lib.rs façade content."""
    sub_crates = [b for b in buckets
                   if b.startswith("touring-hooks-")
                   and b not in ("touring-hooks-facade", "touring-hooks-misc")]
    lines = [
        '//! `touring-hooks` — Façade re-exports for the 8 split sub-crates.',
        '//!',
        '//! Auto-generated by w8_hooks_facade_emitter.py (W8.6).',
        '//! DO NOT add direct code here — extend the relevant sub-crate instead.',
        "",
        "#![forbid(unsafe_code)]",
        "#![deny(missing_docs)]",
        "",
    ]
    for sub in sub_crates:
        mod = sub.replace("touring-hooks-", "")
        lines.append(f"pub use {sub.replace('-', '_')} as {mod};")
    lines.extend([
        "",
        "/// Crate version (semver-compatible with workspace).",
        'pub const VERSION: &str = env!("CARGO_PKG_VERSION");',
        "",
    ])
    return "\n".join(lines)


def emit_facade_cargo(buckets: list[str]) -> str:
    """Generate Cargo.toml [dependencies] section update."""
    sub_crates = sorted(b for b in buckets
                         if b.startswith("touring-hooks-")
                         and b not in ("touring-hooks-facade",
                                        "touring-hooks-misc"))
    deps_lines = [f'{sub} = {{ workspace = true }}' for sub in sub_crates]
    return "\n".join([
        "# AUTO-GENERATED — W8.6 façade [dependencies] section",
        f"# Generated: {sc.now_iso()}",
        "# Replace existing [dependencies] in crates/touring-hooks/Cargo.toml",
        "",
        "[dependencies]",
        *deps_lines,
        "",
    ])


def run(args: sc.Namespace) -> dict:
    """Load plan + emit façade."""
    args.output_dir.mkdir(parents=True, exist_ok=True)
    _STAGING_DIR.mkdir(parents=True, exist_ok=True)
    if not args.plan.exists():
        return {"status": "PLAN_MISSING",
                "hint": "Run w8_hooks_split_planner.py first"}
    plan = json.loads(args.plan.read_text(encoding="utf-8"))
    buckets = list(plan.get("buckets", {}).keys())
    lib_rs = _STAGING_DIR / "w8-touring-hooks-facade-lib.rs"
    lib_rs.write_text(emit_facade_lib(buckets), encoding="utf-8")
    cargo_toml = _STAGING_DIR / "w8-touring-hooks-Cargo.toml"
    cargo_toml.write_text(emit_facade_cargo(buckets), encoding="utf-8")
    manifest = {
        "script": "w8_hooks_facade_emitter",
        "wave": "W8", "subtask_refs": ["W8.6"],
        "timestamp": sc.now_iso(),
        "status": "OK",
        "buckets_in_plan": buckets,
        "sub_crates_reexported": [b for b in buckets
                                     if b.startswith("touring-hooks-")
                                     and b != "touring-hooks-facade"],
        "lib_rs_path": str(lib_rs.relative_to(_ROOT)),
        "cargo_toml_path": str(cargo_toml.relative_to(_ROOT)),
    }
    json_path = args.output_dir / "w8-facade-manifest.json"
    return sc.write_json_report(json_path, manifest, _ROOT)


def _run_and_report(args: sc.Namespace) -> int:
    """Run w8_hooks_facade_emitter, print its summary; the return value is the exit code."""
    result = run(args)
    sc.emit_json(result)
    return 0 if result.get("status") == "OK" else 1


def main() -> int:
    """Entry point of w8_hooks_facade_emitter."""
    return sc.main_frame(build_parser, _run_and_report, __name__)


if __name__ == "__main__":
    raise SystemExit(main())
