"""Shared implementation behind the per-wave ``validate_W<N>.py`` entry points.

Each ``validate_W<N>.py`` is generated by ``plan_lib.emit_scripts.emit_validator_py`` and
carries only what is wave-specific (id, name, gate, the subtask table). Everything that
used to be copied into all fifteen files lives here once: the stub subtask check, the two
wave-level invariants (``cargo check`` + wiring cycles), the report assembly and the
checkpoint/exit-code behavior of ``main``.

``cross_audit_e2e.py`` imports each ``validate_W<N>`` module and calls its ``validate()``;
that contract is unchanged.
"""
from __future__ import annotations

import json
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]
_CHECKPOINTS_DIR = _ROOT / ".claude" / "checkpoints"


def check_subtask(wave_id: str, check_id: str, name: str, validation: str, tdd_test: str) -> dict:
    """Run a single subtask check. Returns a result dict."""
    # TODO: implement real checks. Stub returns False with a clear "not implemented" note.
    return {
        "check": check_id,
        "name": name,
        "validation": validation,
        "tdd_test": tdd_test,
        "passed": False,
        "details": f"Not yet implemented — replace stub with real check during {wave_id} execution.",
    }


def run_cargo_check_workspace() -> bool:
    """Return True if `cargo check --workspace` exits 0."""
    try:
        r = subprocess.run(
            ["cargo", "check", "--workspace"],
            cwd=_ROOT, capture_output=True, timeout=600, check=False,
        )
        return r.returncode == 0
    except Exception:  # noqa: BLE001
        return False


def run_wiring_cycles_zero() -> bool:
    """Return True if no cycles of depth >= 2 detected."""
    try:
        r = subprocess.run(
            ["touring", "wiring", "cycles", "--min-depth", "2", "--format", "json"],
            capture_output=True, timeout=60, check=False,
        )
        if r.returncode != 0:
            return False
        data = json.loads(r.stdout.decode("utf-8") or "{}")
        return int(data.get("cycle_count", 0)) == 0
    except Exception:  # noqa: BLE001
        return False


class WaveValidator:
    """The validator of one wave: its identity, gate and subtask table.

    ``subtasks`` is a sequence of ``(check_id, name, validation, tdd_test)`` rows.
    """

    def __init__(self, wave_id: str, wave_name: str, gate: str, subtasks: tuple) -> None:
        self.wave_id = wave_id
        self.wave_name = wave_name
        self.gate = gate
        self.subtasks = subtasks

    def validate(self) -> dict:
        """Run all validation checks. Returns report dict."""
        results: list[dict] = [check_subtask(self.wave_id, *row) for row in self.subtasks]

        # Wave-level invariants
        cargo_ok = run_cargo_check_workspace()
        cycles_ok = run_wiring_cycles_zero()

        results.append({
            "check": "wave-invariant",
            "name": "cargo check + wiring cycles zero",
            "validation": "cargo check exit 0 + 0 new cycles",
            "tdd_test": "",
            "passed": cargo_ok and cycles_ok,
            "details": f"cargo_check_ok={cargo_ok}, cycles_zero={cycles_ok}",
        })

        passed = sum(1 for r in results if r["passed"])
        total = len(results)
        score = passed / total if total > 0 else 0.0
        status = "PASS" if score >= 0.95 else "WARN" if score >= 0.70 else "FAIL"

        return {
            "wave": self.wave_id,
            "name": self.wave_name,
            "timestamp": datetime.now(UTC).isoformat(),
            "checks_passed": passed,
            "checks_total": total,
            "score": round(score, 4),
            "status": status,
            "gate": self.gate,
            "results": results,
        }

    def main(self) -> None:
        """Entry point. Prints report and saves checkpoint."""
        report = self.validate()
        print(f"\n{'='*60}")
        print(f"  {self.wave_id}: {self.wave_name}")
        print(f"  Score: {report['score']:.4f} ({report['status']})")
        print(f"  Checks: {report['checks_passed']}/{report['checks_total']}")
        print(f"{'='*60}\n")
        for r in report["results"]:
            icon = "[PASS]" if r["passed"] else "[FAIL]"
            print(f"  {icon} {r['check']}: {r['name']}")
            if r["details"]:
                print(f"          {r['details']}")
        cp = _CHECKPOINTS_DIR / f"touring_premium_{self.wave_id}_{datetime.now(UTC).strftime('%Y%m%d')}.json"
        cp.parent.mkdir(parents=True, exist_ok=True)
        cp.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"\n  Checkpoint: {cp}")
        sys.exit(0 if report["status"] in ("PASS", "WARN") else 1)
