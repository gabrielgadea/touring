def emit_subscript_stub(spec: SubscriptSpec) -> str:
    """Emit a sub-script as Python stub with argparse + main + TODO body."""
    # NOTE: indent must match the 8-space common leading of the dedent template
    # below; otherwise textwrap.dedent leaves residual indentation in the output.
    cli_args_lines = "\n".join(
        f'        parser.add_argument("--{arg.split()[0].lstrip("-")}", help={arg!r})'
        for arg in spec.cli_args
    ) if spec.cli_args else "        # No additional CLI args."
    return textwrap.dedent(f'''\
        #!/usr/bin/env python3
        """{spec.purpose}

        Sub-script for wave {spec.wave}, implementing subtasks: {", ".join(spec.subtask_refs)}.

        Auto-generated by generate_plan.py — refine with real implementation when
        executing wave {spec.wave}.

        Inputs
        ------
        {chr(10).join("    - " + i for i in spec.inputs) if spec.inputs else "    (none)"}

        Outputs
        -------
        {chr(10).join("    - " + o for o in spec.outputs) if spec.outputs else "    (none)"}

        Usage
        -----
            python3 {spec.name}.py --help
        """
        from __future__ import annotations

        import argparse
        import json
        import logging
        import subprocess
        import sys
        from datetime import UTC, datetime
        from pathlib import Path

        LOGGER = logging.getLogger(__name__)
        _ROOT = Path(__file__).resolve().parents[2]
        _STAGING_DIR = _ROOT / "scripts" / "touring_premium_refactor_2026" / "staging"
        _BASELINES_DIR = _ROOT / "docs" / "baselines"


        def build_parser() -> argparse.ArgumentParser:
            """CLI parser."""
            parser = argparse.ArgumentParser(
                prog={spec.name!r},
                description={spec.purpose!r},
                formatter_class=argparse.ArgumentDefaultsHelpFormatter,
            )
{cli_args_lines}
            parser.add_argument("-v", "--verbose", action="store_true")
            return parser


        def run() -> dict:
            """Execute the script logic. Returns a result dict for downstream tooling."""
            # TODO: Implement real logic for wave {spec.wave} subtasks {spec.subtask_refs}.
            # This is a STUB — replace with actual implementation when running {spec.wave}.
            LOGGER.warning("STUB execution — not yet implemented. Refer to "
                          f"WAVE {spec.wave} subtask descriptions in "
                          "docs/plans/touring-premium-refactor-2026/.")
            return {{
                "script": {spec.name!r},
                "wave": {spec.wave!r},
                "subtask_refs": {spec.subtask_refs!r},
                "timestamp": datetime.now(UTC).isoformat(),
                "status": "STUB",
                "details": "Replace stub with real implementation during wave execution.",
            }}


        def main() -> int:
            """Entry point."""
            parser = build_parser()
            args = parser.parse_args()
            logging.basicConfig(
                level=logging.DEBUG if args.verbose else logging.INFO,
                format="%(asctime)s [%(levelname)s] %(message)s",
            )
            try:
                result = run()
                print(json.dumps(result, indent=2, ensure_ascii=False))
                return 0
            except KeyboardInterrupt:
                LOGGER.warning("interrupted")
                return 130
            except Exception:  # noqa: BLE001
                LOGGER.exception("error")
                return 1


        if __name__ == "__main__":
            raise SystemExit(main())
        ''')


def emit_all_subscripts(force: bool = False, only_stubs: bool = True) -> list[Path]:
    """Emit all sub-script stubs. Real-impl scripts skipped if file exists (unless force)."""
    written: list[Path] = []
    for spec in SUBSCRIPTS_REGISTRY:
        path = _SCRIPTS_DIR / f"{spec.name}.py"
        if spec.real_impl and path.exists() and not force:
            LOGGER.debug("skip %s (real_impl exists, no --force)", path.name)
            continue
        if only_stubs and spec.real_impl and not force:
            # Keep existing real implementations; don't overwrite
            LOGGER.debug("preserve %s (real_impl)", path.name)
            continue
        content = emit_subscript_stub(spec)
        write_atomic(path, content)
        path.chmod(0o755)
        written.append(path)
        LOGGER.info("  wrote %s (%d bytes)", path.name, len(content.encode("utf-8")))
    return written


def emit_cross_audit_py() -> str:
    """Emit cross_audit_e2e.py: the wave table only.

    The audit itself (import each ``validate_W<N>``, score the 10 weighted dimensions, print,
    checkpoint, exit) is static and lives once in ``cross_audit_common``.
    """
    wave_rows = "".join(
        f'    ("{w.id}", "{w.name}", {len(w.subtasks)}, "{",".join(w.depends_on)}", "{w.rust_changes}"),\n'
        for w in WAVES
    )
    return (
        "#!/usr/bin/env python3\n"
        '"""Cross-audit E2E — touring-premium-refactor-2026.\n'
        "\n"
        "Auto-generated by generate_plan.py — DO NOT edit manually.\n"
        "Regenerate: python3 generate_plan.py --emit-cross-audit\n"
        "\n"
        "Audits 15 waves against 10 weighted quality dimensions.\n"
        '"""\n'
        "from __future__ import annotations\n"
        "\n"
        "import cross_audit_common\n"
        "\n"
        "WAVES_META: list[tuple[str, str, int, str, str]] = [\n"
        f"{wave_rows}"
        "]\n"
        "\n"
        "\n"
        "def main() -> None:\n"
        '    """Run full cross-audit."""\n'
        "    cross_audit_common.main(WAVES_META)\n"
        "\n"
        "\n"
        'if __name__ == "__main__":\n'
        "    main()\n"
    )
