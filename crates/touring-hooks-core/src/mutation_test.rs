/// Stale threshold for the on-disk cache (7 days, per T1 spec).
pub const CACHE_STALE_SECS: u64 = 7 * 24 * 60 * 60;

/// Resolve the cache file for a given package under the touring cache root.
/// `package = None` collapses to `"_workspace"`.
#[must_use]
pub fn cache_path(cache_root: &Path, package: Option<&str>) -> PathBuf {
    let leaf = package.unwrap_or("_workspace");
    cache_root
        .join("mutation-test")
        .join(format!("{leaf}.json"))
}

impl MutationReport {
    /// Whether this report represents an actual measurement.
    ///
    /// False when no mutant was testable: `caught + timeout + survived == 0`.
    /// `unviable` is excluded — a mutant that never compiled was never a test.
    ///
    /// 2026-08-20: `parse_outcomes_json` rejected this case and the CACHE path
    /// did not, so a stored report with `mutants_total: 0` was served straight
    /// back as `ok: true` — and the cache is consulted FIRST, which made the
    /// unguarded path the one that actually ran.
    #[must_use]
    pub fn has_measurement(&self) -> bool {
        self.mutants_killed
            .saturating_add(self.mutants_timeout)
            .saturating_add(self.mutants_survived)
            > 0
    }
}

/// Load a cached [`MutationReport`] when present and fresh (≤ 7 days).
///
/// Returns `Ok(None)` for missing or stale entries (caller re-runs).
///
/// # Errors
///
/// Returns [`MutationError::OutcomesParse`] when the cache file exists but
/// is corrupt — caller may delete it and re-run.
pub fn cache_load(cache_root: &Path, package: Option<&str>) -> Result<Option<MutationReport>> {
    let path = cache_path(cache_root, package);
    if !path.exists() {
        return Ok(None);
    }
    let metadata = fs::metadata(&path)?;
    if let Ok(modified) = metadata.modified()
        && let Ok(age) = modified.elapsed()
        && age.as_secs() > CACHE_STALE_SECS
    {
        return Ok(None);
    }
    let bytes = fs::read(&path)?;
    let report: MutationReport =
        serde_json::from_slice(&bytes).map_err(|e| MutationError::OutcomesParse {
            path: path.clone(),
            source: e,
        })?;
    // A cached non-measurement is still a non-measurement. Treated as a MISS
    // rather than an error: a stale useless entry should make the caller
    // re-run, not fail. Serving it as `ok: true` is what this guards.
    if !report.has_measurement() {
        return Ok(None);
    }
    Ok(Some(report))
}

/// Persist a [`MutationReport`] to the cache atomically (tempfile + rename).
///
/// # Errors
///
/// Filesystem and serialization failures bubble up via [`MutationError::Io`].
pub fn cache_store(
    cache_root: &Path,
    package: Option<&str>,
    report: &MutationReport,
) -> Result<()> {
    let path = cache_path(cache_root, package);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let bytes = serde_json::to_vec_pretty(report).map_err(|e| MutationError::OutcomesParse {
        path: path.clone(),
        source: e,
    })?;
    let tmp = path.with_extension("json.tmp");
    fs::write(&tmp, &bytes)?;
    fs::rename(&tmp, &path)?;
    Ok(())
}

