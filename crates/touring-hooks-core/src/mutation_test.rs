/// Returns true iff `cargo-mutants` (or `cargo-mutants.exe`) is on PATH.
#[must_use]
pub fn cargo_mutants_available() -> bool {
    which_in_path("cargo-mutants").is_some()
}

fn which_in_path(name: &str) -> Option<PathBuf> {
    let path_var = std::env::var_os("PATH")?;
    for dir in std::env::split_paths(&path_var) {
        let candidate = dir.join(name);
        if candidate.is_file() {
            return Some(candidate);
        }
        // Windows .exe variant — harmless on unix (file won't exist).
        let exe = dir.join(format!("{name}.exe"));
        if exe.is_file() {
            return Some(exe);
        }
    }
    None
}

fn physical_cores() -> u32 {
    // `num_cpus` is already a transitive workspace dep via tokio/rayon ecosystem.
    // Fallback to 1 in pathological environments.
    let n = num_cpus::get_physical();
    u32::try_from(n.max(1)).unwrap_or(1)
}

