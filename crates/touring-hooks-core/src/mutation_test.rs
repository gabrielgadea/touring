#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Write;
    use tempfile::TempDir;

    fn write_outcomes(dir: &Path, body: &str) -> PathBuf {
        let path = dir.join("outcomes.json");
        let mut f = fs::File::create(&path).unwrap();
        f.write_all(body.as_bytes()).unwrap();
        path
    }

    #[test]
    fn kill_rate_zero_when_no_mutants() {
        assert_eq!(compute_kill_rate(0, 0, 0), 0.0);
    }

    #[test]
    fn kill_rate_unviable_excluded() {
        // 8 caught + 2 missed = 10 testable; unviable doesn't enter.
        assert!((compute_kill_rate(8, 2, 0) - 80.0).abs() < f32::EPSILON);
    }

    #[test]
    fn kill_rate_timeout_counts_as_killed() {
        // 6 caught + 4 timeout = 10 detected; 0 missed → 100%.
        assert!((compute_kill_rate(6, 0, 4) - 100.0).abs() < f32::EPSILON);
    }

    #[test]
    fn kill_rate_partial() {
        // 5 caught + 5 missed = 50%.
        assert!((compute_kill_rate(5, 5, 0) - 50.0).abs() < f32::EPSILON);
    }

    #[test]
    fn parse_outcomes_canonical_fixture() {
        let dir = TempDir::new().unwrap();
        let body = r#"{
            "outcomes": [],
            "total_mutants": 100,
            "caught": 80,
            "missed": 15,
            "timeout": 3,
            "unviable": 2,
            "cargo_mutants_version": "26.1.2"
        }"#;
        let path = write_outcomes(dir.path(), body);
        let report = parse_outcomes_json(&path, 80.0, Some("touring-ast".into()), 42).unwrap();
        assert_eq!(report.mutants_total, 100);
        assert_eq!(report.mutants_killed, 80);
        assert_eq!(report.mutants_survived, 15);
        assert_eq!(report.mutants_timeout, 3);
        assert_eq!(report.mutants_unviable, 2);
        // (80 + 3) / (80 + 3 + 15) = 83/98 ≈ 84.69%
        assert!((report.kill_rate - 84.693_88).abs() < 0.01);
        assert!(report.passed_threshold); // 84.69 >= 80
        assert_eq!(report.elapsed_secs, 42);
        assert_eq!(report.threshold, 80.0);
        assert_eq!(report.package.as_deref(), Some("touring-ast"));
        assert_eq!(report.cargo_mutants_version, "26.1.2");
    }

    #[test]
    fn parse_outcomes_threshold_fail() {
        let dir = TempDir::new().unwrap();
        let body = r#"{"total_mutants":10,"caught":4,"missed":6,"timeout":0,"unviable":0,"cargo_mutants_version":"26.1.2"}"#;
        let path = write_outcomes(dir.path(), body);
        let report = parse_outcomes_json(&path, 80.0, None, 1).unwrap();
        assert!((report.kill_rate - 40.0).abs() < f32::EPSILON);
        assert!(!report.passed_threshold);
    }

    #[test]
    fn parse_outcomes_missing_fails_gracefully() {
        let dir = TempDir::new().unwrap();
        let path = dir.path().join("nope.json");
        let err = parse_outcomes_json(&path, 80.0, None, 0).unwrap_err();
        assert!(matches!(err, MutationError::OutcomesMissing(_)));
    }

    #[test]
    fn parse_outcomes_corrupt_fails_with_parse_error() {
        let dir = TempDir::new().unwrap();
        let path = write_outcomes(dir.path(), "{ not valid json");
        let err = parse_outcomes_json(&path, 80.0, None, 0).unwrap_err();
        assert!(matches!(err, MutationError::OutcomesParse { .. }));
    }

    #[test]
    fn config_resolved_output_dir_default() {
        let cfg = MutationConfig::new(PathBuf::from("/ws"));
        assert_eq!(
            cfg.resolved_output_dir(),
            PathBuf::from("/ws/target/mutants/all")
        );
    }

    #[test]
    fn config_resolved_output_dir_with_package() {
        let mut cfg = MutationConfig::new(PathBuf::from("/ws"));
        cfg.package = Some("touring-ast".into());
        assert_eq!(
            cfg.resolved_output_dir(),
            PathBuf::from("/ws/target/mutants/touring-ast")
        );
    }

    #[test]
    fn config_resolved_output_dir_explicit_override() {
        let mut cfg = MutationConfig::new(PathBuf::from("/ws"));
        cfg.output_dir = Some(PathBuf::from("/tmp/custom"));
        assert_eq!(cfg.resolved_output_dir(), PathBuf::from("/tmp/custom"));
    }

    #[test]
    fn cache_roundtrip() {
        let dir = TempDir::new().unwrap();
        let report = MutationReport {
            mutants_total: 50,
            mutants_killed: 40,
            mutants_survived: 8,
            mutants_timeout: 1,
            mutants_unviable: 1,
            kill_rate: 83.67,
            elapsed_secs: 120,
            passed_threshold: true,
            threshold: 80.0,
            package: Some("touring-ast".into()),
            cargo_mutants_version: "26.1.2".into(),
        };
        cache_store(dir.path(), Some("touring-ast"), &report).unwrap();
        let loaded = cache_load(dir.path(), Some("touring-ast"))
            .unwrap()
            .unwrap();
        assert_eq!(loaded, report);
    }

    #[test]
    fn cache_miss_returns_none() {
        let dir = TempDir::new().unwrap();
        assert!(cache_load(dir.path(), Some("nope")).unwrap().is_none());
    }

    #[test]
    fn cache_path_workspace_collapse() {
        let p = cache_path(Path::new("/cache"), None);
        assert_eq!(p, PathBuf::from("/cache/mutation-test/_workspace.json"));
    }

    #[test]
    fn cache_path_per_package() {
        let p = cache_path(Path::new("/cache"), Some("touring-ast"));
        assert_eq!(p, PathBuf::from("/cache/mutation-test/touring-ast.json"));
    }

    /// Mock CI test: when cargo-mutants is absent, `run_mutation_test`
    /// returns `BinaryNotFound` (graceful degradation, no panic).
    /// Simulated by setting PATH to an empty dir.
    #[test]
    fn ci_mock_no_cargo_mutants_returns_binary_not_found() {
        let dir = TempDir::new().unwrap();
        let original_path = std::env::var_os("PATH");
        // SAFETY: tests with env mutation must not run in parallel with other
        // tests touching PATH; this one only checks our own helper.
        unsafe {
            std::env::set_var("PATH", dir.path());
        }
        let available = cargo_mutants_available();
        if let Some(p) = original_path {
            // SAFETY: restore immediately to minimize cross-test contamination.
            unsafe {
                std::env::set_var("PATH", p);
            }
        }
        assert!(!available, "expected cargo-mutants absent under empty PATH");
    }
}
