//! Wave T1 — `cargo-mutants` wrapper for the touring quality stack.
//!
//! Drives the external `cargo-mutants` binary, parses the
//! `mutants.out/outcomes.json` artifact, and exposes a stable
//! [`MutationReport`] for downstream consumers (R1 repo-score Testing
//! category, T2 CI gate, MCP tool, etc.).
//!
//! # Architecture
//!
//! - [`MutationConfig`] is the input contract (workspace, package filter,
//!   threshold, timeouts, parallelism).
//! - [`MutationReport`] is the deterministic output (counts + kill_rate +
//!   passed_threshold flag).
//! - [`run_mutation_test`] orchestrates `cargo mutants` execution and
//!   reads `outcomes.json` from the produced output directory.
//! - [`parse_outcomes_json`] is the file-only parser — testable without
//!   cargo-mutants installed (mock-friendly).
//! - [`compute_kill_rate`] is pure arithmetic — exhaustively unit-tested.
//! - [`cache_load`] / [`cache_store`] persist reports under
//!   `<cache_root>/mutation-test/<package>.json` keyed by
//!   `(workspace_hash, source_fingerprint)`.
//!
//! # Failure mode
//!
//! When `cargo-mutants` is absent, [`run_mutation_test`] returns
//! `Err(MutationError::BinaryNotFound)` so callers (CI gates, repo-score)
//! can degrade gracefully instead of panicking.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Instant;

use serde::{Deserialize, Serialize};

