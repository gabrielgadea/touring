/// Inputs for a mutation test run. Defaults via [`MutationConfig::new`].
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MutationConfig {
    /// Absolute path to the cargo workspace root (must contain Cargo.toml).
    pub workspace: PathBuf,
    /// Optional `--package` filter (None = whole workspace).
    pub package: Option<String>,
    /// Per-mutant test timeout in seconds (passed as `--timeout`).
    pub timeout_secs: u32,
    /// Parallel jobs (passed as `--jobs`); defaults to physical cores.
    pub jobs: u32,
    /// Kill-rate threshold in percent `[0.0, 100.0]` (e.g. 80.0 = 80% killed).
    pub threshold: f32,
    /// Optional output dir override (cargo-mutants writes `mutants.out/` here).
    /// Defaults to `<workspace>/target/mutants/<package_or_all>`.
    pub output_dir: Option<PathBuf>,
}

impl MutationConfig {
    /// Construct a config with sensible defaults: 60s per-mutant timeout,
    /// physical-core jobs, 80% threshold, default output dir.
    #[must_use]
    pub fn new(workspace: PathBuf) -> Self {
        Self {
            workspace,
            package: None,
            timeout_secs: 60,
            jobs: physical_cores(),
            threshold: 80.0,
            output_dir: None,
        }
    }

    /// Resolve the effective output directory for this config.
    #[must_use]
    pub fn resolved_output_dir(&self) -> PathBuf {
        if let Some(dir) = &self.output_dir {
            return dir.clone();
        }
        let leaf = self.package.clone().unwrap_or_else(|| "all".to_string());
        self.workspace.join("target").join("mutants").join(leaf)
    }
}

/// Deterministic outcome of a mutation test run.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct MutationReport {
    /// Total mutants generated by cargo-mutants (caught + missed + timeout + unviable).
    pub mutants_total: u32,
    /// Mutants caught by the test suite (a test failed when this mutant ran).
    pub mutants_killed: u32,
    /// Mutants survived (no test failed — gap in coverage).
    pub mutants_survived: u32,
    /// Mutants that timed out (counted as caught for kill_rate).
    pub mutants_timeout: u32,
    /// Mutants that failed to compile (excluded from kill_rate denominator).
    pub mutants_unviable: u32,
    /// `(killed + timeout) / (killed + timeout + survived)` in percent `[0,100]`.
    pub kill_rate: f32,
    /// Wall-clock elapsed seconds for the run.
    pub elapsed_secs: u64,
    /// `kill_rate >= threshold`.
    pub passed_threshold: bool,
    /// Threshold used during this run (for downstream context).
    pub threshold: f32,
    /// Package filter used during this run (None = whole workspace).
    pub package: Option<String>,
    /// `cargo-mutants` version reported by the outcomes artifact.
    pub cargo_mutants_version: String,
}

/// Errors surfaced by the wrapper. Conservative variants — callers can
/// degrade per-variant (e.g. `BinaryNotFound` → skip gate, log warning).
#[derive(Debug, thiserror::Error)]
pub enum MutationError {
    /// `cargo-mutants` binary missing from PATH.
    #[error("cargo-mutants binary not found on PATH (install: cargo install cargo-mutants)")]
    BinaryNotFound,
    /// `cargo mutants` exited with a non-zero status that we couldn't classify.
    /// Note: cargo-mutants returns non-zero when MissedMutant exists — that
    /// is normal and parsed as `passed_threshold=false`, not an error.
    #[error("cargo-mutants exit failed (status={status:?}): {stderr}")]
    ExitFailed {
        /// Process exit status code, if the process exited normally.
        status: Option<i32>,
        /// Captured standard error output for diagnosis.
        stderr: String,
    },
    /// `outcomes.json` missing after a run (cargo-mutants likely crashed pre-emit).
    #[error("outcomes.json missing at expected path: {0}")]
    OutcomesMissing(PathBuf),
    /// `outcomes.json` could not be parsed as the expected schema.
    #[error("outcomes.json parse error at {path}: {source}")]
    OutcomesParse {
        /// Path to the `outcomes.json` file that failed to parse.
        path: PathBuf,
        /// The underlying deserialization error.
        #[source]
        source: serde_json::Error,
    },
    /// Filesystem error (cache I/O, dir creation, etc.).
    #[error("filesystem error: {0}")]
    Io(#[from] std::io::Error),
    /// The artifact records no viable mutant, so nothing was measured.
    ///
    /// A run that generates zero testable mutants is a FAILED run, not a
    /// passing one: `compute_kill_rate` yields 0.0 for an empty denominator,
    /// and returning that as a report lets a dead harness read as a measured
    /// score. Origin (2026-08-20): the workspace baseline died on the
    /// iai-callgrind bench target for months, emitting `total_mutants: 0`
    /// while the CLI answered `ok: true` and `repo-score` scored its "testing"
    /// category from that zero.
    #[error(
        "no viable mutants at {path} (total={total}, unviable={unviable}) — \
         the run produced nothing to measure; check the cargo-mutants baseline"
    )]
    NoViableMutants {
        /// Path to the `outcomes.json` that carried no viable mutant.
        path: PathBuf,
        /// Total mutants the artifact reports (may be 0 or all-unviable).
        total: u32,
        /// Mutants that failed to compile, hence never testable.
        unviable: u32,
    },
}

/// Convenience alias matching the rest of the touring codebase.
pub type Result<T> = std::result::Result<T, MutationError>;

// ─────────────────────────────────────────────────────────────────────────────
// outcomes.json schema (private — only what we consume)
// ─────────────────────────────────────────────────────────────────────────────

#[derive(Debug, Deserialize)]
struct OutcomesArtifact {
    #[serde(default)]
    total_mutants: u32,
    #[serde(default)]
    caught: u32,
    #[serde(default)]
    missed: u32,
    #[serde(default)]
    timeout: u32,
    #[serde(default)]
    unviable: u32,
    #[serde(default)]
    cargo_mutants_version: String,
}

// ─────────────────────────────────────────────────────────────────────────────
// Public API
// ─────────────────────────────────────────────────────────────────────────────

/// Compute the canonical kill_rate from the four outcome counts.
///
/// `kill_rate = (killed + timeout) / (killed + timeout + survived)` in percent.
/// `unviable` mutants are excluded from the denominator (they never compiled,
/// so the test suite had no opportunity to detect them).
///
/// Returns 0.0 when the denominator is zero (no testable mutants generated).
#[must_use]
pub fn compute_kill_rate(killed: u32, survived: u32, timeout: u32) -> f32 {
    let detected = killed.saturating_add(timeout);
    let denom = detected.saturating_add(survived);
    if denom == 0 {
        return 0.0;
    }
    let pct = (f64::from(detected) / f64::from(denom)) * 100.0;
    // Clamp to a sane numeric range; arithmetic above guarantees [0, 100].
    pct.clamp(0.0, 100.0) as f32
}

/// Parse a `mutants.out/outcomes.json` file into a [`MutationReport`].
///
/// `threshold` and `package` are stamped into the report for context — they
/// are not validated against the file contents.
///
/// # Errors
///
/// - [`MutationError::OutcomesMissing`] if the file does not exist.
/// - [`MutationError::OutcomesParse`] if the JSON does not match the schema.
pub fn parse_outcomes_json(
    path: &Path,
    threshold: f32,
    package: Option<String>,
    elapsed_secs: u64,
) -> Result<MutationReport> {
    if !path.exists() {
        return Err(MutationError::OutcomesMissing(path.to_path_buf()));
    }
    let bytes = fs::read(path)?;
    let artifact: OutcomesArtifact =
        serde_json::from_slice(&bytes).map_err(|e| MutationError::OutcomesParse {
            path: path.to_path_buf(),
            source: e,
        })?;

    // A zero denominator is the absence of a measurement, never a score of
    // zero — fail loudly instead of handing back a report the caller cannot
    // distinguish from a real one. The same rule is applied to the CACHE path
    // in `cache_load`; both call `has_measurement` so a third caller cannot
    // diverge from the definition.
    if artifact
        .caught
        .saturating_add(artifact.timeout)
        .saturating_add(artifact.missed)
        == 0
    {
        return Err(MutationError::NoViableMutants {
            path: path.to_path_buf(),
            total: artifact.total_mutants,
            unviable: artifact.unviable,
        });
    }

    let kill_rate = compute_kill_rate(artifact.caught, artifact.missed, artifact.timeout);
    let passed_threshold = kill_rate >= threshold;

    Ok(MutationReport {
        mutants_total: artifact.total_mutants,
        mutants_killed: artifact.caught,
        mutants_survived: artifact.missed,
        mutants_timeout: artifact.timeout,
        mutants_unviable: artifact.unviable,
        kill_rate,
        elapsed_secs,
        passed_threshold,
        threshold,
        package,
        cargo_mutants_version: artifact.cargo_mutants_version,
    })
}

/// Run `cargo mutants` end-to-end and return a [`MutationReport`].
///
/// Side effects:
/// - Spawns `cargo mutants` with the configured package/timeout/jobs.
/// - Writes the `mutants.out/` artifact under `config.resolved_output_dir()`.
/// - Returns parsed outcomes (caller decides whether to cache).
///
/// # Errors
///
/// - [`MutationError::BinaryNotFound`] if `cargo-mutants` is not installed.
/// - [`MutationError::ExitFailed`] if cargo itself errored (workspace broken).
/// - [`MutationError::OutcomesMissing`] / [`MutationError::OutcomesParse`] on artifact problems.
pub fn run_mutation_test(config: &MutationConfig) -> Result<MutationReport> {
    if !cargo_mutants_available() {
        return Err(MutationError::BinaryNotFound);
    }

    let out_dir = config.resolved_output_dir();
    fs::create_dir_all(&out_dir)?;

    let started = Instant::now();
    let mut cmd = Command::new("cargo");
    cmd.arg("mutants")
        .arg("--no-shuffle")
        .arg("--output")
        .arg(&out_dir)
        .arg("--timeout")
        .arg(config.timeout_secs.to_string())
        .arg("--jobs")
        .arg(config.jobs.to_string());
    if let Some(pkg) = &config.package {
        cmd.arg("-p").arg(pkg);
    }
    cmd.current_dir(&config.workspace);

    let output = cmd.output().map_err(|e| {
        if e.kind() == std::io::ErrorKind::NotFound {
            MutationError::BinaryNotFound
        } else {
            MutationError::Io(e)
        }
    })?;

    // cargo-mutants exits non-zero when MissedMutant exists. That's not a
    // wrapper error — we still parse outcomes.json. Only hard-classify a
    // failure when outcomes.json is absent AND status is non-zero.
    let outcomes = out_dir.join("mutants.out").join("outcomes.json");
    if !outcomes.exists() && !output.status.success() {
        return Err(MutationError::ExitFailed {
            status: output.status.code(),
            stderr: String::from_utf8_lossy(&output.stderr).to_string(),
        });
    }

    let elapsed = started.elapsed().as_secs();
    parse_outcomes_json(&outcomes, config.threshold, config.package.clone(), elapsed)
}

